#!/usr/bin/env node
// Copies the production Cloudflare D1 data into a Postgres import file for Supabase.
//
//   node scripts/d1-to-supabase.mjs            # reads the remote (production) D1 database
//   node scripts/d1-to-supabase.mjs --local    # reads the local wrangler dev database
//
// Writes supabase/d1-data-import.sql (git-ignored: it contains client data).
// Run that file once in the Supabase SQL editor (or psql) AFTER the schema
// migration. Inserts use ON CONFLICT DO NOTHING, so re-running is safe.
// Expired unanswered questions are skipped (the Worker's cron would delete them).
import { execFileSync } from "node:child_process";
import { writeFileSync, mkdirSync, existsSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import path from "node:path";

export const D1_DATABASE = "taxcomp-unanswered-questions";

// Parents before children, matching the foreign keys in the Supabase schema.
export const TABLE_ORDER = Object.freeze([
  "unanswered_questions",
  "efris_clients", "efris_products", "efris_invoices", "efris_imports", "efris_audit_log",
  "legal_sources", "legal_source_audit",
  "phase6_bootstrap_state", "phase6_organizations", "phase6_users", "phase6_memberships",
  // phase6_sessions / phase6_password_resets are not copied: sign-in moved to
  // Supabase Auth and those tables no longer exist in Supabase.
  "phase6_clients", "phase6_client_access",
  "phase6_client_tax_profiles", "phase6_engagements", "phase6_obligations", "phase6_documents",
  "phase6_compliance_documents", "phase6_document_versions", "phase6_document_reviews",
  "phase6_analysis_proposals", "phase6_scenarios", "phase6_scenario_documents",
  "phase6_scenario_versions", "phase6_reports", "phase6_report_versions", "phase6_audit_log",
  "phase10_usage_daily", "phase11_subscriptions", "phase11_payment_events", "phase11_invoices",
  // Billing (Supabase-only). billing_plans is reference data seeded by the
  // migration; the others are restored after it.
  "billing_plans", "billing_accounts", "billing_subscriptions", "billing_payments",
  // Law register, case repository, intelligence log and assessment challenges
  // (Supabase-only). tax_heads and the seeded register rows come from the
  // migration; ON CONFLICT DO NOTHING keeps them.
  "tax_heads", "law_instruments", "law_provisions", "law_amendments", "law_time_limits",
  "tax_cases", "tax_case_principles", "tax_case_provision_links", "intel_triage_log",
  "assessment_challenges", "assessment_challenge_items", "assessment_challenge_deadlines",
  "assessment_challenge_evidence", "assessment_challenge_drafts", "assessment_challenge_events",
]);

const IDENTIFIER = /^[a-z_][a-z0-9_]*$/;

export function sqlLiteral(value) {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number") {
    if (!Number.isFinite(value)) throw new RangeError(`Cannot export non-finite number ${value}.`);
    return String(value);
  }
  if (typeof value === "boolean") return value ? "1" : "0";
  if (typeof value === "string") {
    if (value.includes("\u0000")) throw new RangeError("Text values cannot contain NUL bytes in Postgres.");
    return `'${value.replaceAll("'", "''")}'`;
  }
  throw new TypeError(`Unsupported value type ${typeof value}.`);
}

/**
 * @param {Record<string, object[]>} rowsByTable
 * @param {{ now?: Date }} options
 * @returns {{ sql: string, summary: Record<string, number>, skipped: Record<string, number>, unknownTables: string[] }}
 */
export function buildImportSql(rowsByTable, { now = new Date(), dropExpiredQuestions = true } = {}) {
  const unknownTables = Object.keys(rowsByTable).filter((name) => !TABLE_ORDER.includes(name));
  const summary = {};
  const skipped = {};
  const lines = [
    "-- Generated by scripts/d1-to-supabase.mjs. Contains client data: do not commit or share.",
    "BEGIN;",
    "SET LOCAL search_path TO taxcomp;",
  ];
  for (const table of TABLE_ORDER) {
    let rows = rowsByTable[table] || [];
    if (table === "unanswered_questions" && dropExpiredQuestions) {
      const cutoff = now.toISOString();
      const kept = rows.filter((row) => typeof row.expires_at === "string" && row.expires_at > cutoff);
      if (kept.length !== rows.length) skipped[table] = rows.length - kept.length;
      rows = kept;
    }
    if (!rows.length) continue;
    const columns = Object.keys(rows[0]);
    for (const column of columns) {
      if (!IDENTIFIER.test(column)) throw new RangeError(`Unexpected column name ${table}.${column}.`);
    }
    lines.push(`-- ${table}: ${rows.length} row(s)`);
    for (const row of rows) {
      const values = columns.map((column) => sqlLiteral(row[column]));
      lines.push(`INSERT INTO ${table} (${columns.join(", ")}) VALUES (${values.join(", ")}) ON CONFLICT DO NOTHING;`);
    }
    summary[table] = rows.length;
  }
  lines.push("COMMIT;", "");
  return { sql: lines.join("\n"), summary, skipped, unknownTables };
}

// Runs npx without a shell so SQL arguments are passed verbatim (cmd.exe would
// otherwise treat characters such as < > | & in the query as operators).
function runNpx(args, options) {
  const npxCli = path.join(path.dirname(process.execPath), "node_modules", "npm", "bin", "npx-cli.js");
  if (process.platform === "win32" && existsSync(npxCli)) {
    return execFileSync(process.execPath, [npxCli, ...args], options);
  }
  return execFileSync("npx", args, options);
}

function wranglerQuery(sql, { remote }) {
  const args = ["--yes", "wrangler@4.158.0", "d1", "execute", D1_DATABASE, remote ? "--remote" : "--local", "--json", "--command", sql];
  const output = runNpx(args, {
    encoding: "utf8",
    maxBuffer: 256 * 1024 * 1024,
    stdio: ["ignore", "pipe", "inherit"],
  });
  const parsed = JSON.parse(output);
  const first = Array.isArray(parsed) ? parsed[0] : parsed;
  if (!first?.success) throw new Error(`wrangler query failed: ${sql}`);
  return first.results || [];
}

async function main() {
  const remote = !process.argv.includes("--local");
  console.error(`Reading ${remote ? "REMOTE (production)" : "local"} D1 database ${D1_DATABASE}...`);
  const tables = wranglerQuery(
    "SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' AND name NOT LIKE '_cf_%' AND name != 'd1_migrations' ORDER BY name",
    { remote },
  ).map((row) => row.name);
  const rowsByTable = {};
  for (const table of tables) {
    if (!IDENTIFIER.test(table)) throw new RangeError(`Unexpected table name ${table}.`);
    rowsByTable[table] = wranglerQuery(`SELECT * FROM ${table}`, { remote });
  }
  const { sql, summary, skipped, unknownTables } = buildImportSql(rowsByTable);
  if (unknownTables.length) {
    console.error(`WARNING: tables not in the Supabase schema were NOT exported: ${unknownTables.join(", ")}`);
  }
  const projectDir = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
  const outFile = path.join(projectDir, "supabase", "d1-data-import.sql");
  mkdirSync(path.dirname(outFile), { recursive: true });
  writeFileSync(outFile, sql, { encoding: "utf8", mode: 0o600 });
  console.error(`Rows exported: ${JSON.stringify(summary)}`);
  if (Object.keys(skipped).length) console.error(`Skipped (expired): ${JSON.stringify(skipped)}`);
  console.error(`Wrote ${outFile}. Run it once in the Supabase SQL editor after the schema migration, then delete it.`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  main().catch((error) => {
    console.error(error instanceof Error ? error.message : error);
    process.exit(1);
  });
}
