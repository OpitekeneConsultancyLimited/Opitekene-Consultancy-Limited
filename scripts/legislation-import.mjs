// Generates idempotent SQL that imports one edition of legislative structure
// (laws, sections, schedules, relations) into the taxcomp legislation tables.
//
//   node scripts/legislation-import.mjs law-index.json \
//     --edition ug-rev-2024 --label "Laws of Uganda, Revised Edition 2024 (FY 2024/25)" \
//     --effective-from 2024-07-01 --effective-to 2025-06-30 > import.sql
//   npx supabase@2.121.0 db query --linked -f import.sql
//
// Re-running is safe: nothing is duplicated, and a record a reviewer has moved
// off "unverified" is never overwritten (a changed heading on such a record is
// left for review). Every insert and change is logged by the history trigger.
// Structure only: this never writes section wording.
import { readFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

/** Inserted sections printed with pre-revision numbers: kept as captured, flagged for official numbering checks. */
export const NUMBERING_CHECK = new Set(["ita:118I", "tpca:40E"]);

export const RELATION_HINTS = [
  // Inferred from section headings; labelled "inferred" until a reviewer confirms them.
  { from: ["ita", "80"], to: ["ita", "88"], kind: "related", note: "Foreign tax credit and the provision giving effect to international agreements." },
  { from: ["ita", "82"], to: ["ita", "137"], kind: "related", note: "Charge on international payments and the withholding provision for international payments." },
  { from: ["ita", "84"], to: ["ita", "138"], kind: "related", note: "Tax on non-resident contractors and the withholding provision for non-resident services contracts." },
  { from: ["ita", "116"], to: ["ita", "117"], kind: "related", note: "Both provisions are in Part XI (Anti-Avoidance)." },
  { from: ["vata", "16"], to: ["vata", "5"], kind: "related", note: "Place of supply of services and the person liable to pay tax." },
  { from: ["tpca", "26"], to: ["tata", "16"], kind: "procedure_next_step", note: "Objection to a tax decision, then application to the Tax Appeals Tribunal for review." },
  { from: ["tpca", "27"], to: ["tata", "14"], kind: "procedure_next_step", note: "Review of an objection decision and the Tribunal's power to review taxation decisions." },
];

function parseArgs(argv) {
  const args = { file: null };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a.startsWith("--")) args[a.slice(2)] = argv[++i];
    else args.file = a;
  }
  return args;
}

const q = (v) => (v === null || v === undefined ? "NULL" : `'${String(v).replace(/'/g, "''")}'`);

function scheduleParts(text) {
  const m = text.match(/^(?:(First|Second|Third|Fourth|Fifth|Sixth)\s+)?Schedules?\s*(\d+[A-Z]?)?\s*[-–—:.]?\s*(.*)$/i);
  if (!m) return { label: "Schedule", title: text };
  const ordinal = m[1] ? `${m[1][0].toUpperCase()}${m[1].slice(1).toLowerCase()} Schedule` : null;
  return { label: ordinal ?? (m[2] ? `Schedule ${m[2]}` : "Schedule"), title: m[3].replace(/\.$/, "").trim() || null };
}

/** Section numbers named in an enabling provision, e.g. "Under sections 116 and 151 of the Income Tax Act". */
export function enablingSections(text) {
  if (!text) return [];
  // Subsections in brackets ("21(1)(z)", "26(11) and (12)") are not separate sections.
  const head = text.replace(/\bof the [^,]*$/i, "").replace(/\([^)]*\)/g, "").replace(/[[\]]/g, "");
  return [...new Set([...head.matchAll(/\b(\d{1,3}[A-Z]?)\b/g)].map((m) => m[1]))];
}

export function buildImportSql(index, edition) {
  const at = edition.importedAt;
  const actor = `import:${edition.id}`;
  const laws = index.instruments;
  const byId = new Map(laws.map((l) => [l.id, l]));
  const parentOf = (law) => (law.kind === "act" ? null : law.id.startsWith("ita-") ? "ita" : law.id.startsWith("vat-") ? "vata" : law.id.startsWith("tpc-") ? "tpca" : law.id.startsWith("nssf-") ? "nssf" : null);
  const sectionId = (lawId, number) => `${edition.id}/${lawId}/${byId.get(lawId)?.kind === "act" ? "s" : "r"}${number}`;
  const numbers = new Map(laws.map((l) => [l.id, new Set(l.parts.flatMap((p) => p.divisions.flatMap((d) => d.items.map((i) => i.section))))]));
  const out = [];

  out.push(`-- Generated by scripts/legislation-import.mjs for edition ${edition.id}. Do not edit by hand.`);
  out.push("SET search_path TO taxcomp;");
  out.push(`INSERT INTO legislation_editions (id, jurisdiction, label, kind, effective_from, effective_to, publication_date, source_reference, coverage_note, verification_status, created_at, updated_at, updated_by)
VALUES (${[q(edition.id), "'UG'", q(edition.label), "'revised_edition'", q(edition.effectiveFrom), q(edition.effectiveTo), q(edition.publicationDate ?? null), q(index.extractedFrom), q(index.caveats.join(" ")), "'unverified'", q(at), q(at), q(actor)].join(", ")})
ON CONFLICT (id) DO NOTHING;`);

  // Laws (stable identity), then the law as it stands in this edition.
  out.push(`INSERT INTO legislation_laws (id, jurisdiction, short_title, category, tax_category, parent_law_id, statute_id, created_at) VALUES`);
  const ordered = [...laws].sort((a, b) => (a.kind === "act" ? 0 : 1) - (b.kind === "act" ? 0 : 1));
  out.push(ordered.map((l) => `  (${[q(l.id), "'UG'", q(l.title.replace(/\s*\(Cap\..*$/, "")), q(l.kind === "act" ? "act" : /\bOrder\b/.test(l.title) ? "order" : "regulations"), q(l.taxCategory), q(parentOf(l)),
    `(SELECT id FROM law_statutes WHERE id = ${q(l.id)})`, q(at)].join(", ")})`).join(",\n"));
  out.push("ON CONFLICT (id) DO NOTHING;");

  out.push(`INSERT INTO legislation_law_versions (id, law_id, edition_id, official_title, chapter, commencement_date, enabling_provision, statutory_instrument, section_count, schedule_count, source_reference, verification_status, updated_at, updated_by) VALUES`);
  out.push(laws.map((l) => `  (${[q(`${edition.id}/${l.id}`), q(l.id), q(edition.id), q(l.title), q(l.cap ? `Cap. ${l.cap}` : null), q(l.commencement), q(l.enablingProvision), q(l.statutoryInstrument), String(l.sectionCount), String(l.schedules.length),
    q(`${l.title}${l.cap ? `, Cap. ${l.cap}` : ""} — ${edition.label}; structure from the printed Arrangement of Sections`), "'unverified'", q(at), q(actor)].join(", ")})`).join(",\n"));
  out.push(`ON CONFLICT (id) DO UPDATE SET official_title = EXCLUDED.official_title, chapter = EXCLUDED.chapter, commencement_date = EXCLUDED.commencement_date,
  enabling_provision = EXCLUDED.enabling_provision, statutory_instrument = EXCLUDED.statutory_instrument, section_count = EXCLUDED.section_count,
  schedule_count = EXCLUDED.schedule_count, updated_at = EXCLUDED.updated_at, updated_by = EXCLUDED.updated_by
WHERE legislation_law_versions.verification_status = 'unverified'
  AND (legislation_law_versions.official_title, legislation_law_versions.chapter, legislation_law_versions.commencement_date, legislation_law_versions.section_count, legislation_law_versions.schedule_count)
   IS DISTINCT FROM (EXCLUDED.official_title, EXCLUDED.chapter, EXCLUDED.commencement_date, EXCLUDED.section_count, EXCLUDED.schedule_count);`);

  // Sections.
  const rows = [];
  for (const l of laws) {
    let position = 0;
    for (const part of l.parts) {
      for (const division of part.divisions) {
        for (const item of division.items) {
          position++;
          const flags = NUMBERING_CHECK.has(`${l.id}:${item.section}`) ? ["numbering-check"] : [];
          rows.push(`  (${[q(sectionId(l.id, item.section)), q(`${edition.id}/${l.id}`), q(item.section), q(item.heading), q(part.part), q(part.title), q(division.title), String(position), q(JSON.stringify(flags)),
            "'unverified'", q(at), q(actor)].join(", ")})`);
        }
      }
    }
  }
  out.push(`INSERT INTO legislation_sections (id, law_version_id, section_number, heading, part_number, part_title, division, position, flags_json, verification_status, updated_at, updated_by) VALUES`);
  out.push(rows.join(",\n"));
  out.push(`ON CONFLICT (id) DO UPDATE SET heading = EXCLUDED.heading, part_number = EXCLUDED.part_number, part_title = EXCLUDED.part_title, division = EXCLUDED.division,
  position = EXCLUDED.position, flags_json = EXCLUDED.flags_json, updated_at = EXCLUDED.updated_at, updated_by = EXCLUDED.updated_by
WHERE legislation_sections.verification_status = 'unverified'
  AND (legislation_sections.heading, legislation_sections.part_number, legislation_sections.part_title, legislation_sections.division, legislation_sections.position, legislation_sections.flags_json)
   IS DISTINCT FROM (EXCLUDED.heading, EXCLUDED.part_number, EXCLUDED.part_title, EXCLUDED.division, EXCLUDED.position, EXCLUDED.flags_json);`);

  // Schedules.
  const schedules = [];
  for (const l of laws) {
    l.schedules.forEach((text, i) => {
      const { label, title } = scheduleParts(text);
      schedules.push(`  (${[q(`${edition.id}/${l.id}/sch${i + 1}`), q(`${edition.id}/${l.id}`), q(label), q(title), String(i + 1), "'unverified'", q(at), q(actor)].join(", ")})`);
    });
  }
  if (schedules.length) {
    out.push(`INSERT INTO legislation_schedules (id, law_version_id, label, title, position, verification_status, updated_at, updated_by) VALUES`);
    out.push(schedules.join(",\n"));
    out.push(`ON CONFLICT (id) DO UPDATE SET label = EXCLUDED.label, title = EXCLUDED.title, position = EXCLUDED.position, updated_at = EXCLUDED.updated_at, updated_by = EXCLUDED.updated_by
WHERE legislation_schedules.verification_status = 'unverified'
  AND (legislation_schedules.label, legislation_schedules.title, legislation_schedules.position) IS DISTINCT FROM (EXCLUDED.label, EXCLUDED.title, EXCLUDED.position);`);
  }

  // Relations. Confirmed: a regulation and the sections named in its own enabling provision.
  const relations = [];
  for (const l of laws) {
    const parent = parentOf(l);
    if (!parent) continue;
    relations.push([`${edition.id}/${l.id}/made-under/${parent}`, l.id, null, parent, null, "made_under", "confirmed", l.enablingProvision ?? "Regulations made under the Act."]);
    for (const n of enablingSections(l.enablingProvision)) {
      if (!numbers.get(parent)?.has(n)) throw new Error(`${l.id}: enabling section ${n} is not in ${parent}`);
      relations.push([`${edition.id}/${l.id}/made-under/${parent}/${n}`, l.id, null, parent, sectionId(parent, n), "made_under", "confirmed", l.enablingProvision]);
    }
  }
  for (const hint of RELATION_HINTS) {
    for (const [lawId, n] of [hint.from, hint.to]) if (!numbers.get(lawId)?.has(n)) throw new Error(`relation hint: ${lawId} s.${n} not in the edition`);
    relations.push([`${edition.id}/${hint.from.join("-")}/${hint.kind}/${hint.to.join("-")}`, hint.from[0], sectionId(...hint.from), hint.to[0], sectionId(...hint.to), hint.kind, "inferred", hint.note]);
  }
  out.push(`INSERT INTO legislation_relations (id, from_law_id, from_section_id, to_law_id, to_section_id, kind, basis, evidence, created_at) VALUES`);
  out.push(relations.map((r) => `  (${r.map((v) => q(v)).join(", ")}, ${q(at)})`).join(",\n"));
  out.push("ON CONFLICT (id) DO NOTHING;");
  return `${out.join("\n")}\n`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const args = parseArgs(process.argv.slice(2));
  if (!args.file || !args.edition || !args.label || !args["effective-from"]) {
    console.error('Usage: node scripts/legislation-import.mjs law-index.json --edition <id> --label "<label>" --effective-from YYYY-MM-DD [--effective-to YYYY-MM-DD] [--publication-date YYYY-MM-DD]');
    process.exit(2);
  }
  const index = JSON.parse(readFileSync(args.file, "utf8"));
  process.stdout.write(buildImportSql(index, {
    id: args.edition, label: args.label, effectiveFrom: args["effective-from"], effectiveTo: args["effective-to"] ?? null,
    publicationDate: args["publication-date"] ?? null, importedAt: args["imported-at"] ?? new Date().toISOString(),
  }));
}
